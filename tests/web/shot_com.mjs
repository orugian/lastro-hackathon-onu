// Screenshot da fila de comunicações (antes e depois de confirmar um envio).
import { chromium } from "playwright";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const out = join(dirname(fileURLToPath(import.meta.url)), "screens");
const base = process.argv[2] ?? "http://127.0.0.1:8000";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto(`${base}/#/comunicacoes`);
await page.waitForSelector(".com-item", { timeout: 30000 });
await page.waitForTimeout(800);
await page.screenshot({ path: join(out, "final-11-comunicacoes.png") });
await page.click(".com-item >> nth=0 >> button.primary");
await page.fill(".com-confirm input", "Fiscal Demonstração (mat. 000000)");
await page.fill(".com-confirm textarea", "Dossiê revisado; indícios B, C e E justificam verificação.");
await page.screenshot({ path: join(out, "final-12-comunicacoes-confirmar.png") });
await page.click(".com-confirm button.primary");
await page.waitForTimeout(1500);
await page.screenshot({ path: join(out, "final-13-comunicacoes-enviado.png") });
await browser.close();
console.log("ok");
